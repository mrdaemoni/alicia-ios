#!/usr/bin/env python3
"""Check the study note's phone-side logic (CL-20261023-study-note-card).

Compiles Alicia/Core/StudyNote.swift (Foundation only) for the Mac and checks:
- it reads the backend's own status shapes (scripts/fixtures/study_note_status.json,
  generated by skills/study_notes.py with invented words);
- the receipt is kept for a retry of the same words and replaced when they change;
- drafts survive a restart and are cleared only on request;
- the Mac's answers map to saved, rejected or unknown.
"""
from pathlib import Path
import json
import os
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
fixture = (root / 'scripts/fixtures/study_note_status.json').read_text()

checks = r'''
import Foundation
setvbuf(stdout, nil, _IOLBF, 0)
var passed = 0
func check(_ ok: Bool, _ message: @autoclosure () -> String) {
    guard ok else { print("FAILED: " + message()); exit(1) }
    passed += 1
}
struct Fixture: Decodable { var due: StudyNoteStatus; var saved: StudyNoteStatus; var none: StudyNoteStatus }
let fixtureText = #"""
FIXTURE
"""#
let f = try! JSONDecoder().decode(Fixture.self, from: Data(fixtureText.utf8))

// 1. The backend's own shapes.
check(f.due.isUsable && f.due.week == 2 && f.due.arm == "after" && !f.due.saved, "Due card reads")
check(f.due.prompts.map(\.id) == ["cost", "not_steered", "steered", "landed", "wrong", "else"], "Six template prompts")
check(f.due.line == "Week 2 note · two minutes, your own words" && f.due.dates == "Oct 25 – Oct 31", "Card line and dates")
check(f.saved.isUsable && f.saved.saved && f.saved.saved_today && f.saved.line == "Week 2 note saved", "Saved card reads")
check(!f.none.isUsable && !f.none.show, "No card on other days")
check(!(try! JSONDecoder().decode(StudyNoteStatus.self, from: Data("{\"show\": true, \"week\": 2}".utf8))).isUsable,
      "A due card without prompts is not shown")

// 2. Receipts: a retry of the same words reuses one; changed words get a new one.
var ids = ["first", "second", "third"].makeIterator()
var draft = StudyNoteDraft(week: 2)
draft.answers["cost"] = "  Invented, with spaces kept.  "
let one = draft.receipt(newID: { ids.next()! })
check(one == "first" && draft.receipt(newID: { ids.next()! }) == "first", "Same words, same receipt")
draft.answers["landed"] = "It meant I kept walking."
check(draft.receipt(newID: { ids.next()! }) == "second", "Changed words, new receipt")
draft.answers["else"] = ""
check(draft.receipt(newID: { ids.next()! }) == "third", "Even a cleared field is a change")

// 3. The body is verbatim: never trimmed; blank answers are left out (the Mac shows them blank).
draft.mornings = "most mornings "
let body = try! JSONSerialization.jsonObject(with: draft.body(requestID: "third")) as! [String: Any]
let answers = body["answers"] as! [String: String]
check(body["request_id"] as? String == "third" && body["week"] as? Int == 2, "Receipt and week")
check(answers["cost"] == "  Invented, with spaces kept.  " && answers["else"] == nil, "Verbatim, blank omitted")
check(body["mornings"] as? String == "most mornings ", "Mornings verbatim")

// 4. Drafts survive a restart and leave only when cleared.
let dir = URL(fileURLWithPath: CommandLine.arguments[1])
let encoded = try! JSONEncoder().encode(draft)
check((try? JSONDecoder().decode(StudyNoteDraft.self, from: encoded)) == draft, "A draft and its receipt survive encoding")
// The atomic store needs a writable staging folder: true on the phone, refused by
// this session's sandbox. Load and clear are checked from a plainly written file.
if StudyNoteDrafts.store(draft, in: dir) {
    print("note: atomic store succeeded here")
} else {
    print("note: atomic store refused by this environment (sandbox); checked on device and in the UI test")
    try! encoded.write(to: StudyNoteDrafts.file(week: 2, in: dir))
}
let back = StudyNoteDrafts.load(week: 2, in: dir)
check(back == draft && back?.requestID == "third", "A kept draft loads with its receipt")
check(StudyNoteDrafts.load(week: 3, in: dir) == nil, "Weeks are separate")
StudyNoteDrafts.clear(week: 2, in: dir)
check(StudyNoteDrafts.load(week: 2, in: dir) == nil, "Cleared on request")

// 5. The Mac's answers.
check(StudyNoteResponse.decode(status: 200, data: Data("{\"ok\": true, \"saved_at\": \"t\"}".utf8)) == .saved(savedAt: "t"), "200 saved")
check(StudyNoteResponse.decode(status: 409, data: Data("{\"ok\": false, \"error\": \"Not saved.\"}".utf8)) == .rejected("Not saved."), "409 rejected with its words")
check(StudyNoteResponse.decode(status: 400, data: Data()) != .unreachable, "400 is a definite refusal")
check(StudyNoteResponse.decode(status: 503, data: Data()) == .unreachable, "503 is unknown: keep and retry")
check(StudyNoteResponse.decode(status: 200, data: Data("{}".utf8)) == .unreachable, "200 without ok is not a save")
check(StudyNoteResponse.decode(status: 0, data: Data()) == .unreachable, "No answer is unknown")
print("\(passed) study note checks passed")
'''.replace('FIXTURE', fixture)

with tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR')) as d:
    (Path(d) / 'main.swift').write_text(checks)
    swiftc = '/Applications/Xcode.app/Contents/Developer/Toolchains/XcodeDefault.xctoolchain/usr/bin/swiftc'
    sdk = '/Applications/Xcode.app/Contents/Developer/Platforms/MacOSX.platform/Developer/SDKs/MacOSX.sdk'
    subprocess.run([swiftc, '-sdk', sdk, '-module-cache-path', d + '/mc', str(root / 'Alicia/Core/StudyNote.swift'),
                    d + '/main.swift', '-o', d + '/checks'], check=True,
                   env=dict(os.environ, DEVELOPER_DIR='/Applications/Xcode.app/Contents/Developer'))
    drafts = Path(d) / 'drafts'
    drafts.mkdir()
    subprocess.run([d + '/checks', str(drafts)], check=True)
