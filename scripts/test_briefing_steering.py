#!/usr/bin/env python3
"""Compile the steerable-briefing planner with the real NarrationDocument and check it.

CL-20261015-steerable-briefing. The fixture is generated by the backend's own
test flow from invented text (scripts/fixtures/steerable_briefing_payload.json),
so these checks also prove the phone and the server read the same payload and
apply the same interpretation rules. No network, audio or app state.
"""
from pathlib import Path
import json
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
fixture = json.loads((root / 'scripts/fixtures/steerable_briefing_payload.json').read_text())
payload = json.dumps({k: fixture[k] for k in ('segments', 'steering', 'title', 'id')})

stub = '''import Foundation
struct SpeechChunk: Hashable {
    var url: URL
    var duration: TimeInterval
    var text: String = ""
    var cues: [NarrationCue] = []
    var timingStatus: String = "unavailable"
    var spokenText: String = ""
    var speechBackend: String = ""
    var clipStart: TimeInterval = 0
    var clipEnd: TimeInterval? = nil
    var piece: BriefingPiece? = nil
}
struct MorningBriefing { var segments: [BriefingSegment] = []; var steering: BriefingSteeringInfo? = nil }
'''

checks = r'''
var passed = 0
func check(_ ok: Bool, _ message: String) { precondition(ok, message); passed += 1 }
struct Payload: Decodable { var segments: [BriefingSegment]; var steering: BriefingSteeringInfo; var title: String; var id: String }
let data = Data(PAYLOAD.utf8)
let p = try! JSONDecoder().decode(Payload.self, from: data)
let segs = p.segments, st = p.steering
let resolve: (String) -> URL? = { URL(string: "https://fixture.invalid" + $0) }
check(segs.count == 3 && segs.allSatisfy { $0.levels == [1, 0, -1] }, "Three segments with three servable levels decode")
check(st.arm == "during" && st.line("higher") == "From higher up, starting with the next sentence", "Steering block and lines decode")
check(segs[0].variants.allSatisfy { $0.isPlayable }, "Every variant is playable")

func meaning(_ c: SteerCommand, _ seg: String, _ s: Int, _ level: Int, phase: String = "during", arm: String? = nil,
             segments: [BriefingSegment]? = nil) -> SteerInterpretation {
    var info = st; if let arm { info.arm = arm }
    return BriefingPlanner.interpret(segments: segments ?? segs, steering: info, command: c, segmentID: seg,
                                     sentence: s, levelBefore: level, phase: phase)
}
// Parity with skills/briefing_steering.py (tests/test_briefing_steering.py InterpretTests).
var r = meaning(.higher, "s01", 0, 0)
check(r.change == "level_changed" && r.level_chosen == 1, "Higher from L0 chooses L+1")
check(r.effective_from == SteerEffect(segment_id: "s01", resume_sentence_index: 1, after_segment_id: "s01",
                                      after_sentence_index: 0, level: 1), "Resume at the first unheard ledger item")
check(r.text == "From higher up, starting with the next sentence" && r.cue_id == "higher", "Higher line and cue")
r = meaning(.lower, "s01", 1, 0)
check(r.effective_from?.segment_id == "s02" && r.effective_from?.resume_sentence_index == 0, "Everything heard: next segment")
check(r.text == "Closer in, starting with the next sentence", "Current segment had the level: plain line")
r = meaning(.higher, "s01", 0, 1)
check(r.change == "no_change_at_limit" && r.text == "Already as high as it goes" && r.cue_id == "limit", "At the top")
check(meaning(.lower, "s01", 0, -1).text == "Already as close in as it goes", "At the bottom")
r = meaning(.again, "s02", 1, -1)
check(r.change == "replay" && r.effective_from?.resume_sentence_index == 1 && r.effective_from?.previous_within_seconds == 1.5, "Again")
r = meaning(.higher, "s03", 1, 0)
check(r.change == "not_applied" && r.reason == "nothing_left", "Nothing left after the last sentence")
var partial = segs; partial[0].variants.removeAll { $0.level == 1 }
r = meaning(.higher, "s01", 0, 0, segments: partial)
check(r.effective_from?.segment_id == "s02" && r.text == "Changed where a version exists; this part has only one", "Partial")
check(meaning(.higher, "s01", 0, 0, arm: "after").reason == "arm_after", "After arm refuses a during press")
r = meaning(.lower, "s03", 1, 0, phase: "after_end", arm: "after")
check(r.effective_from == SteerEffect(segment_id: "s01", resume_sentence_index: 0, level: -1, replay: true), "After-end replay")
check(meaning(.higher, "s01", 0, 0, phase: "after_end").reason == "arm_during", "During arm refuses an after-end press")

// The initial path: every chunk, title included, word timing intact.
let path = BriefingPlanner.path(segs, dial: 0, fromSegment: 0, resolve: resolve)
let chunkCount = segs.map { $0.variant(0)!.chunks.count }.reduce(0, +)
check(path.count == chunkCount && path.allSatisfy { $0.clipStart == 0 && $0.clipEnd == nil }, "Initial path is whole L0 chunks")
check(path[0].text.hasPrefix(p.title + "."), "Segment 1 keeps its spoken title")
let text = BriefingPlanner.narration(path)
let doc = NarrationDocument(text: text, chunks: path)
check(doc.hasWordTiming && doc.paragraphs.count == 4, "Narration: title paragraph plus one per segment, timed")

// A Higher during s01's first sentence: cut after it, resume L+1 at sentence 1.
let base = segs[0].variant(0)!, higher = segs[0].variant(1)!
let press = base.sentences[0].start + 0.5
let sw = BriefingPlanner.switchPoint(base, chunk: 0, time: press)
check(sw.sentence == 0 && sw.cut != nil && sw.cut! > base.sentences[0].end && sw.cut! < base.sentences[1].start + 0.01,
      "Cut falls in the gap after the sentence being heard")
let late = BriefingPlanner.switchPoint(base, chunk: 0, time: base.sentences[0].end - 0.1)
check(late.sentence == 1, "Too close to the end: the change waits one more sentence")
var heard = path[0]; heard.clipEnd = sw.cut!; heard.duration = sw.cut! - heard.clipStart
let tail = BriefingPlanner.pieces(segs[0], variant: higher, fromSentence: 1, resolve: resolve, eventID: "e1", cause: "steer")
  + BriefingPlanner.path(segs, dial: 1, fromSegment: 1, resolve: resolve)
let first = tail[0]
check(first.clipStart > 0 && first.piece?.fromSentence == 1 && first.piece?.eventID == "e1", "Resume piece starts at sentence 1")
check(first.text.hasPrefix(higher.sentences[1].text), "Resume text begins exactly at the sentence")
check(first.cues.allSatisfy { $0.start >= 0 && $0.end <= first.duration + 0.05 }, "Cues are shifted into the piece")
check(first.cues.first?.text == higher.sentences[1].text.components(separatedBy: " ").first, "First cue is the sentence's first word")
let steered = [heard] + tail
let steeredDoc = NarrationDocument(text: BriefingPlanner.narration(steered), chunks: steered)
check(steeredDoc.hasWordTiming && steeredDoc.paragraphs.count == 4, "Steered path still aligns, paragraph per segment")
check(BriefingPlanner.narration(steered).hasPrefix(BriefingPlanner.narration([path[0]]).prefix(40)), "Heard prefix text unchanged")
check(tail.dropFirst().allSatisfy { $0.piece?.level == 1 }, "Later segments follow the new dial")

// Untimed sentences fall back to chunk starts, never skipping text.
var untimed = higher; untimed.sentences = untimed.sentences.map { var s = $0; s.timed = false; return s }
let place = BriefingPlanner.entry(untimed, sentence: 1)
check(place.clip == 0 && place.sentence == 0, "Untimed entry repeats from the chunk start")
check(BriefingPlanner.switchPoint(untimed, chunk: 0, time: 0.2).cut == nil, "Untimed cut waits for the chunk end")

// Again: within the threshold of a sentence start, the previous sentence.
check(BriefingPlanner.againTarget(base, chunk: 0, time: base.sentences[1].start + 0.4, within: 1.5) == 0, "Again early: previous")
check(BriefingPlanner.againTarget(base, chunk: 0, time: base.sentences[1].start + 2.0, within: 1.5) == 1, "Again later: this one")
check(BriefingPlanner.entrySentence(segs[2], from: 0, after: 1, to: 1) == nil, "Everything heard: nil")

// Cues are pieces with no text, so they never enter the narration.
let cue = BriefingPlanner.cue("higher", steering: st, resolve: resolve)
check(cue?.piece?.isCue == true && cue!.text.isEmpty && BriefingPlanner.narration([cue!] + path) == text, "Cue is silent text")
// Every consequence branch, as data (BriefingPlanner.consequence).
func outcome(_ m: SteerInterpretation, path: [SpeechChunk], piece: Int = 0, current: Int = 0, sentence: Int = 0,
             cut: Double? = nil, fileTime: Double = 0, dial: Int = 0, ended: Bool = false, segments: [BriefingSegment]? = nil)
    -> (action: BriefingPlanner.Action, dial: Int) {
    BriefingPlanner.consequence(m, segments: segments ?? segs, steering: st, path: path, pieceIndex: piece, current: current,
        sentence: sentence, cut: cut, fileTime: fileTime, dial: dial, ended: ended, eventID: "e2", resolve: resolve)
}
var o = outcome(meaning(.higher, "s01", 0, 0), path: path, sentence: 0, cut: sw.cut, fileTime: press)
if case .replaceFuture(let cur, let t, let immediate) = o.action {
    check(o.dial == 1 && !immediate && cur?.clipEnd == sw.cut, "Higher: the sounding piece ends after the sentence")
    check(cur?.text == BriefingPlanner.scalars(path[0].text, 0, base.sentences[0].end_char), "Heard text runs to the cut sentence")
    check(t.first?.piece?.isCue == true && t[1].piece?.fromSentence == 1 && t[1].piece?.eventID == "e2"
          && t[1].piece?.cause == "steer", "Higher: cue, then L+1 from the unheard item, naming the event")
    check(t.dropFirst(2).allSatisfy { $0.piece?.level == 1 }, "Higher: later segments at L+1")
} else { check(false, "Higher should replace the future") }
o = outcome(meaning(.lower, "s01", 1, 0), path: path, sentence: 1, cut: nil)
if case .replaceFuture(let cur, let t, _) = o.action {
    check(cur == nil && t.first?.piece?.isCue == true && t[1].piece?.segmentID == "s02" && t[1].piece?.level == -1
          && t[1].piece?.eventID == "e2", "Everything heard: cue, then s02 at L-1")
} else { check(false, "Lower should replace the future") }
o = outcome(meaning(.higher, "s01", 0, 0, segments: partial), path: BriefingPlanner.path(partial, dial: 0, fromSegment: 0, resolve: resolve),
            segments: partial)
if case .replaceFuture(let cur, let t, _) = o.action {
    let firstS02 = t.firstIndex { $0.piece?.segmentID == "s02" }
    check(cur == nil && firstS02 != nil && t[firstS02! - 1].piece?.isCue == true && t[firstS02!].piece?.eventID == "e2",
          "Partial: this part finishes, the cue and the change begin at s02")
} else { check(false, "Partial should replace the future") }
let againAt = base.sentences[1].start + 2.0
o = outcome(meaning(.again, "s01", 1, 0), path: path, current: 1, sentence: 1, fileTime: againAt)
if case .replaceFuture(let cur, let t, let immediate) = o.action {
    check(immediate && cur?.clipEnd == againAt && t[1].piece?.fromSentence == 1 && o.dial == 0, "Again: now, from this sentence")
} else { check(false, "Again should replace the future now") }
o = outcome(meaning(.higher, "s01", 0, 1), path: BriefingPlanner.path(segs, dial: 1, fromSegment: 0, resolve: resolve),
            sentence: 0, cut: 2.0, dial: 1)
if case .replaceFuture(_, let t, _) = o.action {
    check(t.first?.piece?.isCue == true && t[1].piece?.level == 1 && t[1].piece?.eventID == "", "Limit: cue, same level, no new event")
} else { check(false, "Limit should confirm with a cue") }
o = outcome(meaning(.lower, "s03", 1, 0, phase: "after_end", arm: "after"), path: path, piece: path.count - 1, sentence: 1, ended: true)
if case .restart(let pieces) = o.action {
    check(o.dial == -1 && pieces.first?.piece?.isCue == true && pieces[1].piece?.segmentID == "s01" && pieces[1].piece?.level == -1
          && pieces[1].piece?.cause == "replay_at_end" && pieces[1].text.hasPrefix(p.title), "After-end Lower replays it all, closer in")
} else { check(false, "After-end Lower should restart") }
o = outcome(meaning(.higher, "s01", 0, 0, arm: "after"), path: path)
if case .none = o.action { check(o.dial == 0, "A refused press changes nothing") } else { check(false, "Refused should do nothing") }
check(MorningBriefing(segments: segs, steering: st).isSteerable, "A segmented, enabled briefing is steerable")
var off = st; off.arm = "off"
check(!MorningBriefing(segments: segs, steering: off).isSteerable && !MorningBriefing(segments: [], steering: st).isSteerable,
      "Off or unsegmented: the single track plays")
print("\(passed) steerable briefing planner checks passed")
'''

with tempfile.TemporaryDirectory() as d:
    source = stub + (root / 'Alicia/Core/NarrationDocument.swift').read_text() + \
        (root / 'Alicia/Core/BriefingSteering.swift').read_text() + \
        '\nlet PAYLOAD = ' + json.dumps(payload) + '\n' + checks
    p = Path(d) / 'check.swift'
    p.write_text(source)
    subprocess.run(['swiftc', str(p), '-o', d + '/checks'], check=True)
    subprocess.run([d + '/checks'], check=True)
